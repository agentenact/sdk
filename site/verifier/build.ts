/**
 * Builds the browser bundle for the live verifier from the PACKAGE'S OWN
 * source (../../src) — not a reimplementation, not dist/. Run with:
 *
 *   bun run site/verifier/build.ts
 *
 * Output: site/public/verifier/agentenact.js (committed; regenerate this
 * script any time src/verify.ts, src/record.ts, src/create.ts or
 * src/adapters/stellar.ts changes).
 *
 * Why this file generates an intermediate entry instead of importing
 * ../../src directly with relative specifiers: repo root package.json has
 * "sideEffects": false alongside an "exports" map. With that combination,
 * `bun build` (both the CLI and Bun.build()) fails to RESOLVE a *relative*
 * import that crosses out of site/verifier into ../../src — it silently
 * emits a broken bundle (dangling `export { verifyRecord }` with no
 * definition, still exit code 0, no error) instead of throwing. This was
 * isolated by bisecting repo root's package.json field by field in a
 * throwaway /tmp reproduction; sideEffects:false + exports is the trigger,
 * and — this is the part that took a binary search of package.json fields to
 * find — it is NOT about the import specifier being relative vs absolute.
 * It is about the ENTRY FILE ITSELF living inside that package's directory
 * tree at all. Any bundle entrypoint located under repo root (where
 * sideEffects:false + exports live) gets its own exports silently dead-code
 * eliminated — Bun treats the entry as "no side effects, therefore
 * shakeable," even though an entry's exports are by definition the bundle's
 * public output. `bun build` exits 0 either way; the only symptom is a
 * suspiciously tiny output with dangling `export { name }` and no
 * definition. Fix: write the generated entry OUTSIDE repo root (os.tmpdir),
 * with absolute imports into ../../src so it still finds the real source
 * regardless of the temp file's location. The imported files themselves
 * (verify.ts, record.ts, stellar.ts) are NOT entries, so their being under
 * the same package.json is fine — confirmed by inspecting the output for
 * `function verifyRecord` / `function createStellarAdapter` with real bodies.
 */
import { rm, writeFile } from 'node:fs/promises';
import { mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const here = import.meta.dir;
const srcDir = path.resolve(here, '../../src');
const outDir = path.resolve(here, '../public/verifier');
const generatedEntry = path.join(os.tmpdir(), `agentenact-verifier-entry-${Date.now()}.ts`);

const entrySource = `// AUTO-GENERATED by site/verifier/build.ts — do not edit, do not commit.
// Lives OUTSIDE repo root on purpose (see build.ts for why).
export { verifyRecord } from ${JSON.stringify(path.join(srcDir, 'verify.ts'))};
export { parseRecord, sha256Hex, decodeRecordHeader, canonicalBytes } from ${JSON.stringify(path.join(srcDir, 'record.ts'))};
export { createStellarAdapter } from ${JSON.stringify(path.join(srcDir, 'adapters/stellar.ts'))};
export { createStellarAgent } from ${JSON.stringify(path.join(srcDir, 'create.ts'))};
export { Keypair, Networks, TransactionBuilder } from ${JSON.stringify(path.join(here, 'sdk.ts'))};
`;

async function main() {
  await writeFile(generatedEntry, entrySource, 'utf8');
  try {
    await mkdir(outDir, { recursive: true });
    const result = await Bun.build({
      entrypoints: [generatedEntry],
      target: 'browser',
      format: 'esm',
      minify: true,
      naming: 'agentenact.js',
    });
    if (!result.success) {
      for (const log of result.logs) console.error(log);
      throw new Error('agentenact verifier bundle failed');
    }
    for (const output of result.outputs) {
      const dest = path.join(outDir, path.basename(output.path));
      await Bun.write(dest, output);
      const bytes = (await Bun.file(dest).arrayBuffer()).byteLength;
      console.log(`wrote ${path.relative(process.cwd(), dest)} (${(bytes / 1024).toFixed(1)} kB)`);
    }
  } finally {
    await rm(generatedEntry, { force: true });
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
